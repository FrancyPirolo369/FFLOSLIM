def rebuild_a_from_mixed_sigma_1d(
    *,
    k_axis: np.ndarray,
    w_axis: np.ndarray,
    re_mix: np.ndarray,
    im_mix: np.ndarray,
    mu_sigma: float,
    mass: float,
    eta_g: float,
    convention: str,
    sigma0_mode: str = "fermi",
    sigma0_density_kmax: float = 5.53,
    sigma0_density_tol: float = 1.0e-5,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, float, float]:
    k = np.asarray(k_axis, dtype=float)
    w = np.asarray(w_axis, dtype=float)
    re_mix = np.asarray(re_mix, dtype=float)
    im_mix = np.minimum(np.asarray(im_mix, dtype=float), 0.0)
    w_ref_idx = int(np.argmin(np.abs(w)))
    sigma0_w = float(w[w_ref_idx])
    sigma0_mode_l = str(sigma0_mode).strip().lower()
    if sigma0_mode_l == "density":
        # High-P closure: do NOT pin a quasiparticle at (kF, 0).  Solve the
        # scalar shift s so that the occupied density of the rebuilt A matches
        # the Luttinger target N = m*mu/2 (n(k) integrated to kmax, i.e. the
        # contact-repair window).  n(s) is monotone increasing in s (raising s
        # lowers every pole), so bisection is safe.  This is the polaron-to-
        # molecule-safe replacement of the Fermi-surface pin: at high P the
        # minority physical mu sits far below the band bottom and pinning
        # ReSigma(kF,0) manufactures a Fermi surface the state does not have.
        target = float(mass) * float(mu_sigma) / 2.0
        kmax = float(sigma0_density_kmax)
        kw = np.where(k <= kmax, k, 0.0)
        occ = w <= 0.0
        xi = k[:, None] ** 2 / float(mass) - float(mu_sigma)

        def occupied_density(s: float) -> float:
            g = 1.0 / (w[None, :] - xi - (re_mix - s) - 1j * im_mix + 1j * float(eta_g))
            a = spectral_from_g(g, str(convention))
            nk = np.trapezoid(a[:, occ], w[occ], axis=1)
            return float(np.trapezoid(nk * kw, k))

        # Start from the fermi-pin value as the initial guess and bracket.
        k_fermi = float(np.sqrt(max(float(mass) * float(mu_sigma), 0.0)))
        re_at_kF = np.array(
            [float(np.interp(k_fermi, k, re_mix[:, j])) for j in range(re_mix.shape[1])]
        )
        s_guess = float(np.interp(0.0, w, re_at_kF))
        lo, hi = s_guess - 1.0, s_guess + 1.0
        n_lo, n_hi = occupied_density(lo), occupied_density(hi)
        for _ in range(60):
            if n_lo <= target:
                break
            lo -= 2.0
            n_lo = occupied_density(lo)
        for _ in range(60):
            if n_hi >= target:
                break
            hi += 2.0
            n_hi = occupied_density(hi)
        if not (n_lo <= target <= n_hi):
            raise RuntimeError(
                f"sigma0 density mode: could not bracket target {target:.6f} "
                f"(n({lo:.2f})={n_lo:.6f}, n({hi:.2f})={n_hi:.6f})"
            )
        tol = float(sigma0_density_tol)
        sigma0 = 0.5 * (lo + hi)
        for _ in range(80):
            sigma0 = 0.5 * (lo + hi)
            n_mid = occupied_density(sigma0)
            if abs(n_mid - target) <= tol:
                break
            if n_mid < target:
                lo = sigma0
            else:
                hi = sigma0
        re_shifted = re_mix - sigma0
        sigma_mix = re_shifted + 1j * im_mix
        g = 1.0 / (w[None, :] - xi - sigma_mix + 1j * float(eta_g))
        a_mix = spectral_from_g(g, str(convention))
        return a_mix, re_mix, im_mix, float(sigma0), sigma0_w
    if sigma0_mode_l in {"fermi", "fermi_exact"}:
        # Pin the real-part shift EXACTLY at (kF, omega=0): sigma0 = ReSigma(kF, 0),
        # evaluated by interpolation (smooth ReSigma -> stable across iterations,
        # no single-index jumps, AND no bias). This makes the Luttinger kF coincide
        # with the free kF, so the density (and the polarization P_meas) come out
        # right by themselves. A +-10% k-average biased sigma0 by ~0.013, shifting
        # kF_L and inflating P_meas by ~5% (P=0.30 -> 0.316; exact -> 0.303).
        k_fermi = float(np.sqrt(max(float(mass) * float(mu_sigma), 0.0)))
        # ReSigma(kF, w): interpolate each omega-column at k_fermi, then at omega=0.
        re_at_kF = np.array(
            [float(np.interp(k_fermi, k, re_mix[:, j])) for j in range(re_mix.shape[1])]
        )
        sigma0 = float(np.interp(0.0, w, re_at_kF))
        # sigma0 AUDIT: an error delta on sigma0 feeds the density DIRECTLY
        # (unpinned kF: dn_sigma ~ -delta/2 per spin). Estimate the k-interp
        # error as |quadratic - linear| on the omega~0 column and report it.
        try:
            j0 = int(np.argmin(np.abs(np.asarray(w, dtype=float))))
            col = np.asarray(re_mix[:, j0], dtype=float)
            i0 = int(np.clip(np.searchsorted(k, k_fermi), 1, k.size - 2))
            kk3 = np.asarray(k[i0 - 1:i0 + 2], dtype=float)
            c3 = col[i0 - 1:i0 + 2]
            quad = float(np.polyval(np.polyfit(kk3, c3, 2), k_fermi))
            lin = float(np.interp(k_fermi, k, col))
            print(f"[sigma0-audit] mu={float(mu_sigma):.3f} sigma0={sigma0:+.6f} "
                  f"k-interp err~{abs(quad - lin):.2e} (dn budget ~ same order)", flush=True)
        except Exception:
            pass
    elif sigma0_mode_l == "fermi_window":
        # r24 compatibility/audit mode: average ReSigma(k,0) over a broad
        # neighbourhood of the free kF.  This is deliberately kept as an
        # explicit switch so we can separate the sigma0 change from the rest
        # of the r25 fixes without editing the pipeline again.
        k_fermi = float(np.sqrt(max(float(mass) * float(mu_sigma), 0.0)))
        dk = float(np.median(np.diff(k))) if k.size > 1 else 0.0
        kF_tol = max(0.10 * k_fermi, 3.0 * dk)
        near_kF = np.abs(k - k_fermi) <= kF_tol
        if not np.any(near_kF):
            near_kF[int(np.argmin(np.abs(k - k_fermi)))] = True
        sigma0 = float(np.mean(re_mix[near_kF, w_ref_idx]))
    elif sigma0_mode_l == "none":
        sigma0 = 0.0
    else:
        raise ValueError(f"Unsupported sigma0_mode '{sigma0_mode}'.")

    re_shifted = re_mix - sigma0
    sigma_mix = re_shifted + 1j * im_mix
    xi = k[:, None] ** 2 / float(mass) - float(mu_sigma)
    g = 1.0 / (w[None, :] - xi - sigma_mix + 1j * float(eta_g))
    a_mix = spectral_from_g(g, str(convention))
    return a_mix, re_mix, im_mix, sigma0, sigma0_w




def rebuild_a_from_saved_sigma_grid(
    *,
    k_axis: np.ndarray,
    w_grid: np.ndarray,
    re_sigma: np.ndarray,
    im_sigma: np.ndarray,
    mu_sigma: float,
    mass: float,
    eta_g: float,
    convention: str,
    sigma0: float,
) -> np.ndarray:
    """Rebuild A on the exact omega grid where ReSigma/ImSigma are saved."""
    k = np.asarray(k_axis, dtype=float)
    w = np.asarray(w_grid, dtype=float)
    re_s = np.asarray(re_sigma, dtype=float)
    im_s = np.asarray(im_sigma, dtype=float)
    if w.ndim == 1:
        xi = k[:, None] ** 2 / float(mass) - float(mu_sigma)
        g = 1.0 / (
            w[None, :]
            - xi
            - (re_s - float(sigma0))
            - 1j * im_s
            + 1j * float(eta_g)
        )
        return spectral_from_g(g, str(convention))
    if w.ndim != 2 or w.shape != re_s.shape or w.shape != im_s.shape:
        raise ValueError(
            "row-local omega rebuild expects w/ReS/ImS with matching 2D shapes; "
            f"got w{w.shape}, ReS{re_s.shape}, ImS{im_s.shape}"
        )
    xi = k[:, None] ** 2 / float(mass) - float(mu_sigma)
    g = 1.0 / (
        w
        - xi
        - (re_s - float(sigma0))
        - 1j * im_s
        + 1j * float(eta_g)
    )
    return spectral_from_g(g, str(convention))






def select_sigma_k_indices(
    k_axis: np.ndarray,
    n_target: int,
    *,
    spin: str,
    physics: Physics,
    mu_internal: float,
    q_feature: float,
) -> np.ndarray:
    """Choose reduced Sigma k-rows while preserving physical feature locations."""
    k = np.asarray(k_axis, dtype=float)
    nk = int(k.size)
    n = int(n_target)
    if n <= 0 or n >= nk:
        return np.arange(nk, dtype=int)

    base = set(np.round(np.linspace(0, nk - 1, max(2, n))).astype(int).tolist())

    spin_l = str(spin).strip().lower()
    mu_external = float(physics.mu_up if spin_l == "up" else physics.mu_down)
    kf_external = float(np.sqrt(max(float(physics.mass) * mu_external, 0.0)))
    kf_internal = float(np.sqrt(max(float(physics.mass) * float(mu_internal), 0.0)))

    features = [float(k[0]), 0.0, kf_external, kf_internal, float(k[-1])]
    if np.isfinite(float(q_feature)):
        q = abs(float(q_feature))
        features.extend(
            [
                q,
                abs(q - kf_internal),
                q + kf_internal,
                abs(q - kf_external),
                q + kf_external,
            ]
        )

    feature_idx: set[int] = set()
    for feat in features:
        if not np.isfinite(feat):
            continue
        idx = int(np.argmin(np.abs(k - float(feat))))
        for j in (idx - 1, idx, idx + 1):
            if 0 <= j < nk:
                base.add(j)
                feature_idx.add(j)

    idx_all = np.array(sorted(base), dtype=int)
    if idx_all.size <= n:
        return idx_all

    # Keep feature anchors first; thin the uniform background if the requested
    # reduced grid is very small.  In production, use sigma_nk ~ 40-80.
    keep = sorted(feature_idx)
    if len(keep) >= n:
        return np.array(sorted(keep)[:n], dtype=int)

    remaining = [i for i in idx_all.tolist() if i not in feature_idx]
    need = n - len(keep)
    if remaining:
        pick = np.round(np.linspace(0, len(remaining) - 1, min(need, len(remaining)))).astype(int)
        keep.extend([remaining[int(i)] for i in pick])
    return np.array(sorted(set(keep)), dtype=int)








def find_qp_poles_dyson(
    A: np.ndarray,
    re_sigma: np.ndarray,
    w: np.ndarray,
    k: np.ndarray,
    mu: float,
    mass: float,
    sigma0: float = 0.0,
) -> np.ndarray:
    """QP pole per k via the shifted Dyson zero-crossing.

    The saved/rebuilt spectral function uses

        G^-1 = omega - xi_k - (ReSigma(k,omega) - sigma0) + i(...)

    so the pole-refind grid must use the same shifted denominator.  Otherwise
    the enrichment can be centered on a pole of a different Green's function.

    w must be 1D (shared base grid). Falls back to argmax when no zero is found
    (deep incoherent tail or numerical issues).
    """
    w = np.asarray(w, dtype=float)
    A = np.asarray(A, dtype=float)
    re_sigma = np.asarray(re_sigma, dtype=float)
    k = np.asarray(k, dtype=float)
    xi = k * k / float(mass) - float(mu)   # bare dispersion ξ_k = k²/m − μ
    re_shifted = re_sigma - float(sigma0)

    poles = np.empty(len(k), dtype=float)
    for ik in range(len(k)):
        f = w - xi[ik] - re_shifted[ik]    # shifted Dyson residual on base grid
        # Find all sign-change intervals
        signs = np.sign(f)
        crossings = np.where(np.diff(signs) != 0)[0]  # left index of each bracket
        if len(crossings) == 0:
            # No zero found — fall back to argmax of A
            poles[ik] = float(w[int(np.argmax(A[ik]))])
            continue
        # Linear interpolation to refine each zero
        zeros = []
        for ic in crossings:
            f0, f1 = f[ic], f[ic + 1]
            w0, w1 = w[ic], w[ic + 1]
            denom = f1 - f0
            if abs(denom) < 1e-30:
                zeros.append(0.5 * (w0 + w1))
            else:
                zeros.append(float(w0 - f0 * (w1 - w0) / denom))
        # Among all zeros, pick the one with largest A (QP peak)
        best = max(zeros, key=lambda wz: float(np.interp(wz, w, A[ik])))
        poles[ik] = best
    return poles


def _build_w_row(
    w_base: np.ndarray,
    pole: float,
    half_width: float,
    n_local: int,
    *,
    zero_protect_half_width: float | None = None,
    occupied_protect_min: float | None = None,
) -> np.ndarray:
    """Build a single per-k omega row: protected zero grid + local pole grid.

    The dangerous rows are precisely those whose quasiparticle pole is near
    omega=0.  Therefore we must *not* skip pole enrichment inside the protected
    zero window.  Instead, keep the original base nodes around zero and add the
    local shifted-Dyson pole nodes on top, removing only far-tail/background
    nodes to keep the row length equal to len(w_base).

    At large k the occupation is controlled by a small broad shoulder at
    negative omega, not by the positive QP pole. If pole enrichment steals too
    many occupied-side base nodes, k^4 n(k) develops an artificial post-cut
    kink. occupied_protect_min keeps that shoulder resolved without increasing
    the saved row length.
    """
    w = np.unique(np.asarray(w_base, dtype=float))
    n_w = int(w.size)
    if n_w == 0:
        return w

    hw = float(max(half_width, 1.0e-10))
    n_loc = int(max(n_local, 2))
    if zero_protect_half_width is None:
        zero_protect_half_width = 4.0 * hw
    zero_protect_half_width = float(max(zero_protect_half_width, 0.0))

    if not np.isfinite(float(pole)) or not (float(w[0]) <= float(pole) <= float(w[-1])):
        return w.copy()

    protected_mask = np.abs(w) < zero_protect_half_width
    if occupied_protect_min is not None and np.isfinite(float(occupied_protect_min)):
        occ_min = float(min(occupied_protect_min, 0.0))
        protected_mask = protected_mask | ((w >= occ_min) & (w <= 0.0))
    w_protected = w[protected_mask]
    enrichment = np.linspace(
        max(float(pole) - hw, float(w[0])),
        min(float(pole) + hw, float(w[-1])),
        n_loc,
        dtype=float,
    )
    # r33: with POLE_REFIND_SNAP_DW>0 quantize enrichment nodes to integer
    # multiples of dw so refined rows stay on the commensurate micro-lattice
    # (dw=1e-3 is far below any physical width in play).
    _snap_dw = float(os.environ.get("POLE_REFIND_SNAP_DW", "0") or 0.0)
    if _snap_dw > 0.0:
        enrichment = np.unique(
            np.clip(np.round(enrichment / _snap_dw) * _snap_dw, float(w[0]), float(w[-1]))
        )

    # Keep the original zero grid and the local pole window.  Tail/background
    # nodes are the only budget that can be thinned away.
    anchors = np.unique(np.concatenate([w_protected, enrichment]))
    if anchors.size >= n_w:
        idx = np.round(np.linspace(0, anchors.size - 1, n_w)).astype(int)
        return np.asarray(anchors[idx], dtype=float)

    # Exclude protected occupied/zero nodes from the thinnable base pool. Exact
    # duplicates with enrichment are harmless because the final unique removes
    # them; if that leaves the row short, we add the nearest remaining base
    # nodes below.
    w_thinnable = w[~protected_mask]
    n_keep = max(0, n_w - anchors.size)
    if w_thinnable.size > n_keep:
        if n_keep > 0:
            idx = np.round(np.linspace(0, w_thinnable.size - 1, n_keep)).astype(int)
            w_thinnable = w_thinnable[idx]
        else:
            w_thinnable = np.array([], dtype=float)

    row = np.unique(np.concatenate([anchors, w_thinnable]))
    if row.size < n_w:
        # Duplicates between enrichment and retained base points can make the
        # row slightly short.  Fill from the remaining base nodes, preferring
        # points closest to omega=0 because they matter most for n(k).
        missing = n_w - row.size
        remaining = np.setdiff1d(w, row, assume_unique=False)
        if remaining.size:
            order = np.argsort(np.abs(remaining))
            row = np.unique(np.concatenate([row, remaining[order[:missing]]]))

    if row.size >= n_w:
        return np.asarray(row[:n_w], dtype=float)

    # Extremely defensive fallback: preserve monotonic shape if the base grid
    # itself was pathological.
    out = np.empty(n_w, dtype=float)
    out[:row.size] = row
    out[row.size:] = row[-1]
    return out


def rebuild_omega_per_k(
    w_base: np.ndarray,
    poles_per_k: np.ndarray,
    half_width: float | np.ndarray,
    n_local: int,
    *,
    zero_protect_half_width: float | None = None,
    occupied_protect_min: float | None = None,
) -> np.ndarray:
    """Build a per-k omega grid (2D, shape n_k x n_w).

    Each row is the shared base grid enriched locally around that k's QP pole.
    All rows have the same length (len(w_base)); budget is neutral per row.
    """
    w_base = np.asarray(w_base, dtype=float)
    poles = np.asarray(poles_per_k, dtype=float)
    if np.ndim(half_width) == 0:
        widths = np.full(poles.shape, float(half_width), dtype=float)
    else:
        widths = np.asarray(half_width, dtype=float)
        if widths.shape != poles.shape:
            raise ValueError(f"pole half-width shape {widths.shape} does not match poles {poles.shape}")
    rows = [
        _build_w_row(
            w_base,
            float(p),
            float(hw),
            n_local,
            zero_protect_half_width=zero_protect_half_width,
            occupied_protect_min=occupied_protect_min,
        )
        for p, hw in zip(poles, widths)
    ]
    n_w = len(w_base)
    # All rows should be length n_w after budget-neutral construction; pad/trim
    # with edge-repeat if deduplication made a row slightly shorter.
    out = np.empty((len(rows), n_w), dtype=float)
    for i, row in enumerate(rows):
        if len(row) >= n_w:
            out[i] = row[:n_w]
        else:
            out[i, :len(row)] = row
            out[i, len(row):] = row[-1]
    return out


def pole_refind_half_widths_from_im_sigma(
    *,
    w_axis: np.ndarray,
    im_sigma: np.ndarray,
    poles: np.ndarray,
    eta_g: float,
    min_half_width: float,
    width_factor: float,
) -> np.ndarray:
    """Choose per-row pole windows wide enough to include the spectral decay."""
    w = np.asarray(w_axis, dtype=float)
    im_s = np.asarray(im_sigma, dtype=float)
    poles = np.asarray(poles, dtype=float)
    widths = np.full(poles.shape, float(max(min_half_width, 1.0e-10)), dtype=float)
    factor = float(max(width_factor, 0.0))
    if factor <= 0.0:
        return widths
    for ik, pole in enumerate(poles):
        if not np.isfinite(float(pole)):
            continue
        gamma_eff = float(eta_g) + max(0.0, -float(np.interp(float(pole), w, im_s[ik])))
        if np.isfinite(gamma_eff):
            widths[ik] = max(widths[ik], factor * gamma_eff)
    return widths


def interp_pchip(
    arr: np.ndarray,
    w_old: np.ndarray,
    w_new: np.ndarray,
) -> np.ndarray:
    """Per-k PCHIP interpolation (nk, nw_old) → (nk, nw_new).

    w_old and w_new may each be 1D (shared) or 2D (per-k, shape nk x nw).
    PCHIP is shape-preserving (no overshoot), safe for sigma and A near QP poles.
    """
    from scipy.interpolate import PchipInterpolator
    arr = np.asarray(arr, dtype=float)
    w_old = np.asarray(w_old, dtype=float)
    w_new = np.asarray(w_new, dtype=float)
    nk = arr.shape[0]
    nw_new = w_new.shape[-1]
    out = np.empty((nk, nw_new), dtype=float)
    for ik in range(nk):
        wo = w_old[ik] if w_old.ndim == 2 else w_old
        wn = w_new[ik] if w_new.ndim == 2 else w_new
        y = np.asarray(arr[ik], dtype=float)
        finite = np.isfinite(y) & np.isfinite(wo)
        if not bool(np.all(finite)):
            if int(np.count_nonzero(finite)) >= 2:
                y = np.interp(wo, wo[finite], y[finite])
            elif int(np.count_nonzero(finite)) == 1:
                y = np.full_like(wo, float(y[finite][0]), dtype=float)
            else:
                y = np.zeros_like(wo, dtype=float)
        out[ik] = PchipInterpolator(wo, y, extrapolate=True)(wn)
    return out










