"""Compute Sigma(k,omega) from the spectral pair-fermion convolution.

Implements the Enss-style spectral representation

    Im Sigma^R_sigma(k,omega)
      = -pi ∫ d^2p/(2pi)^2 ∫ d eps
            [f(eps) + b(omega+eps)]
            A_pair(|k+p|, omega+eps) A_{bar sigma}(p, eps)

in 2D with imbalanced chemical potentials.

The pair spectral function is taken from the analytic pair propagator
Gamma(Q, Omega+i0), i.e.

    A_pair(Q,Omega) = -(1/pi) Im Gamma^R(Q,Omega).

The internal fermion spectral function can be either:
  - free: narrow Lorentzian approximation to a delta peak
  - cube: the opposite-spin A(k,omega) cube from the existing pipeline

Re Sigma is reconstructed from Im Sigma using the same piecewise-linear
principal-value KK as the Pi pipeline.
"""

