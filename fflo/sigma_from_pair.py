def fermi_function(x: np.ndarray, temperature: float) -> np.ndarray:
    t = float(temperature)
    xx = np.asarray(x, dtype=float)
    if t <= 0.0:
        return (xx < 0.0).astype(float)
    y = xx / t
    out = np.empty_like(y)
    pos = y > 40.0
    neg = y < -40.0
    mid = ~(pos | neg)
    out[pos] = 0.0
    out[neg] = 1.0
    out[mid] = 1.0 / (np.exp(y[mid]) + 1.0)
    return out


def bose_function(x: np.ndarray, temperature: float) -> np.ndarray:
    t = float(temperature)
    xx = np.asarray(x, dtype=float)
    if t <= 0.0:
        return -(xx < 0.0).astype(float)
    y = xx / t
    out = np.empty_like(y)
    small = np.abs(y) < 1.0e-6
    pos = y > 40.0
    neg = y < -40.0
    mid = ~(small | pos | neg)
    out[pos] = 0.0
    out[neg] = -1.0
    out[small] = 1.0 / np.where(y[small] == 0.0, np.inf, y[small])
    out[mid] = 1.0 / np.expm1(y[mid])
    return out


def thermal_kernel(eps: np.ndarray, omega: float, temperature: float) -> np.ndarray:
    eps_arr = np.asarray(eps, dtype=float)
    return fermi_function(eps_arr, float(temperature)) + bose_function(float(omega) + eps_arr, float(temperature))




def _sigma_thermal_kernel_scalar_zero_temp(eps_mid: float, omega: float) -> float:
    eps_val = float(eps_mid)
    omega_val = float(omega)
    delta = max(1.0e-12, 1.0e-10 * (1.0 + abs(omega_val)))

    def _raw(x: float) -> float:
        return float((x < 0.0)) + float(-(omega_val + x < 0.0))

    is_zero_kink = np.isclose(eps_val, 0.0, atol=delta, rtol=0.0)
    is_minus_omega_kink = np.isclose(eps_val, -omega_val, atol=delta, rtol=0.0)
    if is_zero_kink or is_minus_omega_kink:
        left = _raw(eps_val - delta)
        right = _raw(eps_val + delta)
        return 0.5 * (left + right)
    return _raw(eps_val)


def _insert_eps_anchors_rows(
    x: np.ndarray,
    y_rows: np.ndarray,
    anchors: np.ndarray | list[float] | tuple[float, ...],
) -> tuple[np.ndarray, np.ndarray]:
    x_aug = np.asarray(x, dtype=float).reshape(-1)
    y_aug = np.asarray(y_rows, dtype=float)
    if y_aug.ndim != 2 or y_aug.shape[1] != x_aug.size:
        raise ValueError("y_rows must be 2D with shape (n_rows, x.size).")
    if x_aug.size < 2:
        return x_aug, y_aug

    dx_min = np.min(np.diff(x_aug))
    tol = max(1.0e-12, 1.0e-8 * float(dx_min))
    anchors_arr = np.asarray(anchors, dtype=float).reshape(-1)
    anchors_arr = anchors_arr[np.isfinite(anchors_arr)]
    if anchors_arr.size == 0:
        return x_aug, y_aug

    anchors_arr = np.unique(anchors_arr)
    anchors_arr = anchors_arr[(anchors_arr > float(x_aug[0]) + tol) & (anchors_arr < float(x_aug[-1]) - tol)]
    for aval in anchors_arr.tolist():
        if np.any(np.abs(x_aug - float(aval)) <= tol):
            continue
        j = int(np.searchsorted(x_aug, float(aval), side="left"))
        if not (0 < j < x_aug.size):
            continue
        x0 = float(x_aug[j - 1])
        x1 = float(x_aug[j])
        t = (float(aval) - x0) / max(x1 - x0, 1.0e-14)
        new_col = (1.0 - t) * y_aug[:, j - 1] + t * y_aug[:, j]
        x_aug = np.insert(x_aug, j, float(aval))
        y_aug = np.insert(y_aug, j, new_col, axis=1)
    return x_aug, y_aug


def _trapz_axis_panel_kernel_sigma(
    y_prod: np.ndarray,
    x: np.ndarray,
    omega: float,
) -> np.ndarray:
    x_aug, y_aug = _insert_eps_anchors_rows(x, y_prod, [0.0, -float(omega)])
    if x_aug.size < 2:
        return np.zeros(y_aug.shape[0], dtype=float)

    out = np.zeros(y_aug.shape[0], dtype=float)
    break_vals = [0.0, -float(omega)]
    break_idx: list[int] = [0]
    for aval in sorted(set(float(v) for v in break_vals if np.isfinite(v))):
        matches = np.where(np.isclose(x_aug, float(aval), atol=1.0e-12, rtol=0.0))[0]
        if matches.size > 0:
            idx = int(matches[0])
            if 0 < idx < x_aug.size - 1:
                break_idx.append(idx)
    break_idx.append(x_aug.size - 1)
    break_idx = sorted(set(break_idx))

    for i in range(len(break_idx) - 1):
        lo = int(break_idx[i])
        hi = int(break_idx[i + 1])
        if hi <= lo:
            continue
        x_seg = x_aug[lo : hi + 1]
        y_seg = y_aug[:, lo : hi + 1]
        eps_mid = 0.5 * (float(x_seg[0]) + float(x_seg[-1]))
        kval = float(_sigma_thermal_kernel_scalar_zero_temp(eps_mid, float(omega)))
        if kval == 0.0:
            continue
        out += kval * _trapz_axis(y_seg, x_seg, axis=1)
    return out




def pair_momentum_sum(p: np.ndarray, k_ext: float, phi: np.ndarray) -> np.ndarray:
    p2 = np.asarray(p, dtype=float)[:, None]
    phi2 = np.asarray(phi, dtype=float)[None, :]
    q2 = p2 * p2 + float(k_ext) * float(k_ext) + 2.0 * p2 * float(k_ext) * np.cos(phi2)
    return np.sqrt(np.maximum(q2, 0.0))


def pair_spectral_function(q_query: np.ndarray, omega_query: np.ndarray, eta_pair: float) -> np.ndarray:
    qq = np.asarray(q_query, dtype=float)
    ww = np.asarray(omega_query, dtype=float)
    qb, wb = np.broadcast_arrays(qq, ww)
    try:
        g = analytical_gamma(qb, wb + 1j * float(eta_pair))
        g_arr = np.asarray(g, dtype=complex)
        if g_arr.shape != qb.shape:
            g_arr = np.broadcast_to(g_arr, qb.shape).astype(complex, copy=False)
    except Exception:
        flat = np.empty(qb.size, dtype=complex)
        qf = qb.ravel()
        wf = wb.ravel()
        for i, (qv, wv) in enumerate(zip(qf, wf)):
            flat[i] = complex(analytical_gamma(float(qv), complex(float(wv), float(eta_pair))))
        g_arr = flat.reshape(qb.shape)
    return -(1.0 / np.pi) * np.imag(g_arr)


def load_pair_table(path: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    with np.load(path) as d:
        q = np.asarray(d["q"], dtype=float)
        omega = np.asarray(d["omega"], dtype=float)
        a_pair = np.asarray(d["A_pair"], dtype=float)
    if q.ndim != 1 or omega.ndim != 1 or a_pair.ndim != 2:
        raise ValueError(f"Invalid pair table shapes in {path}: q{q.shape}, omega{omega.shape}, A_pair{a_pair.shape}")
    if a_pair.shape != (q.size, omega.size):
        raise ValueError(f"A_pair shape mismatch in {path}: expected {(q.size, omega.size)}, got {a_pair.shape}")
    return q, omega, a_pair


def estimate_pair_q_feature(path: Path) -> float:
    with np.load(path) as d:
        q = np.asarray(d["q"], dtype=float)
        omega = np.asarray(d["omega"], dtype=float)
        if q.ndim != 1 or omega.ndim != 1 or q.size == 0 or omega.size == 0:
            return np.nan
        i0 = int(np.argmin(np.abs(omega)))
        if "ReInvGamma" in d.files:
            re_inv = np.asarray(d["ReInvGamma"], dtype=float)
            if re_inv.shape == (q.size, omega.size):
                return float(q[int(np.argmin(np.abs(re_inv[:, i0])))])
        if "A_pair" in d.files:
            a_pair = np.asarray(d["A_pair"], dtype=float)
            if a_pair.shape == (q.size, omega.size):
                return float(q[int(np.argmax(np.abs(a_pair[:, i0])))])
    return np.nan


