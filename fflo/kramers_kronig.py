def vacuum_pi_from_cutoff(
    omega: np.ndarray,
    *,
    q: float,
    eps0: float,
    mu_up: float,
    mu_dn: float,
    eta_gamma: float,
    cutoff: float,
) -> np.ndarray:
    """Bare vacuum bubble at finite cutoff, defined so g0_const - Pi_vac = g0_inverse."""
    g0_const = g0_constant_from_cutoff(float(cutoff), float(eps0))
    g0_inv = g0_inverse(
        np.asarray(omega, dtype=float),
        q=float(q),
        eps0=float(eps0),
        mu_up=float(mu_up),
        mu_dn=float(mu_dn),
        eta_gamma=float(eta_gamma),
    )
    return np.asarray(float(g0_const) - g0_inv, dtype=complex)






def g0_constant_from_cutoff(cutoff: float, eps0: float) -> float:
    cutoff_val = float(cutoff)
    eps0_val = float(eps0)
    if not np.isfinite(cutoff_val) or cutoff_val <= 0.0:
        raise ValueError(f"Need positive finite cutoff to define bare g0, got {cutoff_val!r}.")
    if not np.isfinite(eps0_val) or eps0_val <= 0.0:
        raise ValueError(f"Need positive finite eps0 to define bare g0, got {eps0_val!r}.")
    return float(-(1.0 / (8.0 * np.pi)) * np.log((cutoff_val * cutoff_val + eps0_val) / eps0_val))







