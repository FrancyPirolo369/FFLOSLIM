def _scalar_from_npz(data: np.lib.npyio.NpzFile, keys: list[str], default: float = np.nan) -> float:
    for k in keys:
        if k in data.files:
            v = np.asarray(data[k]).reshape(-1)
            if v.size > 0:
                return float(v[0])
    return float(default)


def load_cube_physics(path: Path) -> tuple[float, float, float]:
    with np.load(path) as data:
        eps0 = _scalar_from_npz(data, ["eps0", "epsilon_0"], default=np.nan)
        mu_up = _scalar_from_npz(data, ["mu_up"], default=np.nan)
        mu_dn = _scalar_from_npz(data, ["mu_dn", "mu_down"], default=np.nan)
    return float(eps0), float(mu_up), float(mu_dn)


def load_cube_a_convention(path: Path) -> str:
    with np.load(path) as data:
        if "a_convention" not in data.files:
            return "minus2_im"
        val = np.asarray(data["a_convention"]).reshape(-1)
        if val.size == 0:
            return "minus2_im"
        raw = val[0]
        if isinstance(raw, bytes):
            return raw.decode("utf-8", errors="replace")
        return str(raw)


def normalize_spectral_weight(a_vals: np.ndarray, convention: str) -> tuple[np.ndarray, str]:
    conv = str(convention).strip()
    if conv == "minus2_im":
        return np.asarray(a_vals, dtype=float) / (2.0 * np.pi), "minus2_im -> divided by 2pi"
    if conv == "minus1_over_pi_im":
        return np.asarray(a_vals, dtype=float), "minus1_over_pi_im -> unchanged"
    return np.asarray(a_vals, dtype=float), f"{conv or 'unknown'} -> assumed unchanged"


def normalize_spectral_rows(
    a_vals: np.ndarray,
    omega_axis: np.ndarray,
    convention: str,
    *,
    enabled: bool = True,
    row_norm_floor: float = 5.0e-2,
) -> tuple[np.ndarray, str]:
    """Convert A convention and enforce the row sum rule on usable k rows.

    The floor prevents rows with almost no captured spectral support from being
    blown up into fake spectra when the quasiparticle peak lies outside the
    finite omega box. Rows below the floor are left convention-normalized only.
    """
    arr, desc = normalize_spectral_weight(a_vals, convention)
    if not bool(enabled):
        return arr, f"{desc}; row normalization disabled"

    w = np.asarray(omega_axis, dtype=float)
    if arr.ndim != 2 or w.ndim not in (1, 2) or arr.shape[1] != w.shape[-1]:
        raise ValueError(
            "normalize_spectral_rows expects A shape (n_k,n_omega) and matching omega axis; "
            f"got A{arr.shape}, omega{w.shape}"
        )

    if w.ndim == 2:
        row_weight = np.array([np.trapezoid(arr[ik], w[ik]) for ik in range(arr.shape[0])])
    else:
        row_weight = np.trapezoid(arr, w, axis=1)
    floor = float(max(row_norm_floor, 0.0))
    good = np.isfinite(row_weight) & (row_weight > floor)
    out = np.array(arr, dtype=float, copy=True)
    out[good] = out[good] / row_weight[good, None]
    return (
        out,
        f"{desc}; row-normalized {int(np.count_nonzero(good))}/{row_weight.size} rows "
        f"(floor={floor:.3g}, weight min/max={float(np.nanmin(row_weight)):.6g}/{float(np.nanmax(row_weight)):.6g})",
    )




def bilinear_eval_with_support(
    k_query: np.ndarray | float,
    w_query: np.ndarray | float,
    k_axis: np.ndarray,
    w_axis: np.ndarray,
    akw: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Evaluate A(k,ω) at query points via interpolation.

    w_axis may be 1D (shared grid, classic bilinear) or 2D (n_k, n_w) for
    per-k omega grids.  In the 2D case the call pattern is assumed to be
    k_query shape (n_p, 1) and w_query shape (1, n_eps) — i.e. each row of
    k_query uses a single k value for all ε — so we vectorise over ε per row.
    """
    k_ax = np.asarray(k_axis, dtype=float)
    w_ax = np.asarray(w_axis, dtype=float)
    kq = np.asarray(k_query, dtype=float)
    wq = np.asarray(w_query, dtype=float)

    if w_ax.ndim == 1:
        # --- original shared-grid bilinear path ---
        kqb, wqb = np.broadcast_arrays(kq, wq)
        shp = kqb.shape
        kf = kqb.ravel()
        wf = wqb.ravel()

        in_k = (kf >= float(k_ax[0])) & (kf <= float(k_ax[-1]))
        in_w = (wf >= float(w_ax[0])) & (wf <= float(w_ax[-1]))
        inside = in_k & in_w

        out = np.zeros_like(kf, dtype=float)
        if np.any(inside):
            ki = np.searchsorted(k_ax, kf[inside], side="right") - 1
            wi = np.searchsorted(w_ax, wf[inside], side="right") - 1
            ki = np.clip(ki, 0, k_ax.size - 2)
            wi = np.clip(wi, 0, w_ax.size - 2)
            k0 = k_ax[ki]; k1 = k_ax[ki + 1]
            w0 = w_ax[wi]; w1 = w_ax[wi + 1]
            tk = (kf[inside] - k0) / np.maximum(k1 - k0, 1.0e-14)
            tw = (wf[inside] - w0) / np.maximum(w1 - w0, 1.0e-14)
            a00 = akw[ki, wi]; a10 = akw[ki + 1, wi]
            a01 = akw[ki, wi + 1]; a11 = akw[ki + 1, wi + 1]
            out[inside] = (
                (1.0 - tk) * (1.0 - tw) * a00
                + tk * (1.0 - tw) * a10
                + (1.0 - tk) * tw * a01
                + tk * tw * a11
            )
        return out.reshape(shp), inside.reshape(shp)

    # --- per-k omega grid path (w_ax is 2D, shape n_k x n_w) ---
    # Expected call: kq shape (n_p, 1), wq shape (1, n_eps)
    kqb, wqb = np.broadcast_arrays(kq, wq)
    shp = kqb.shape
    n_p, n_eps = shp

    w_lo = w_ax[:, 0]   # per-row lower bound
    w_hi = w_ax[:, -1]  # per-row upper bound

    k_lo, k_hi = float(k_ax[0]), float(k_ax[-1])

    out = np.zeros((n_p, n_eps), dtype=float)
    inside = np.zeros((n_p, n_eps), dtype=bool)

    kf = kqb[:, 0]   # (n_p,)
    wf = wqb[0, :]   # (n_eps,)

    in_k = (kf >= k_lo) & (kf <= k_hi)

    ki = np.searchsorted(k_ax, kf, side="right") - 1
    ki = np.clip(ki, 0, k_ax.size - 2)
    tk = (kf - k_ax[ki]) / np.maximum(k_ax[ki + 1] - k_ax[ki], 1.0e-14)

    # Vectorized (2026-09-20): group query rows by shared k-bucket index
    # instead of looping per row (mirrors the bucketing already used in
    # _rowlocal_bilinear_pairs). Bit-for-bit identical to the previous
    # per-row Python loop, verified on captured production call arguments
    # (see scratchpad gammafix_candidate/verify_fast_bilinear.py); ~3.3-3.6x
    # faster since np.interp is called once per unique bucket instead of
    # once per query point.
    valid_ip = np.flatnonzero(in_k)
    if valid_ip.size:
        ki_valid = ki[valid_ip]
        for index in np.unique(ki_valid):
            rows = valid_ip[ki_valid == index]
            w0 = w_ax[index]
            w1 = w_ax[index + 1]
            in_w = (wf >= max(float(w0[0]), float(w1[0]))) & (wf <= min(float(w0[-1]), float(w1[-1])))
            inside[rows] = in_w
            if not np.any(in_w):
                continue
            cols = np.flatnonzero(in_w)
            a0 = np.interp(wf[cols], w0, akw[index])
            a1 = np.interp(wf[cols], w1, akw[index + 1])
            tk0 = tk[rows][:, None]
            out[np.ix_(rows, cols)] = (1.0 - tk0) * a0[None, :] + tk0 * a1[None, :]

    return out.reshape(shp), inside.reshape(shp)


def fermi_zero_temp(x: np.ndarray | float) -> np.ndarray:
    return (np.asarray(x, dtype=float) < 0.0).astype(float)


def _kernel_kink_tol(eps: np.ndarray | float, omega: float) -> float:
    eps_arr = np.asarray(eps, dtype=float).reshape(-1)
    finite = eps_arr[np.isfinite(eps_arr)]
    if finite.size >= 2:
        diffs = np.diff(np.unique(np.sort(finite)))
        diffs = diffs[diffs > 0.0]
        if diffs.size > 0:
            return max(1.0e-12, 0.25 * float(np.min(diffs)))
    return max(1.0e-12, 1.0e-10 * (1.0 + abs(float(omega))))


def _medium_kernel_scalar_midpoint_zero_temp(eps: float, omega: float) -> float:
    eps_val = float(eps)
    omega_val = float(omega)
    delta = max(1.0e-12, 1.0e-10 * (1.0 + abs(omega_val)))

    def _raw_med(x: float) -> float:
        return float(fermi_zero_temp(x) + fermi_zero_temp(omega_val - x))

    is_zero_kink = np.isclose(eps_val, 0.0, atol=delta, rtol=0.0)
    is_omega_kink = np.isclose(eps_val, omega_val, atol=delta, rtol=0.0)
    if is_zero_kink or is_omega_kink:
        left = _raw_med(eps_val - delta)
        right = _raw_med(eps_val + delta)
        return 0.5 * (left + right)
    return _raw_med(eps_val)


def thermal_kernel_zero_temp(eps: np.ndarray, omega: float) -> np.ndarray:
    eps_arr = np.asarray(eps, dtype=float)
    fe = fermi_zero_temp(eps_arr)
    fwe = fermi_zero_temp(float(omega) - eps_arr)
    med = fe + fwe
    tol = _kernel_kink_tol(eps_arr, float(omega))
    kink_mask = np.isclose(eps_arr, 0.0, atol=tol, rtol=0.0) | np.isclose(
        eps_arr, float(omega), atol=tol, rtol=0.0
    )
    if np.any(kink_mask):
        med = np.asarray(med, dtype=float).copy()
        for idx in np.where(kink_mask)[0]:
            med[idx] = _medium_kernel_scalar_midpoint_zero_temp(float(eps_arr[idx]), float(omega))
    return med - 1.0


def medium_kernel_zero_temp(eps: np.ndarray, omega: float) -> np.ndarray:
    eps_arr = np.asarray(eps, dtype=float)
    fe = fermi_zero_temp(eps_arr)
    fwe = fermi_zero_temp(float(omega) - eps_arr)
    med = fe + fwe
    tol = _kernel_kink_tol(eps_arr, float(omega))
    kink_mask = np.isclose(eps_arr, 0.0, atol=tol, rtol=0.0) | np.isclose(
        eps_arr, float(omega), atol=tol, rtol=0.0
    )
    if np.any(kink_mask):
        med = np.asarray(med, dtype=float).copy()
        for idx in np.where(kink_mask)[0]:
            med[idx] = _medium_kernel_scalar_midpoint_zero_temp(float(eps_arr[idx]), float(omega))
    return med


def impi_prefactor_sign() -> float:
    """Prefactor multiplying I_total_scaled to get ImPi on real frequencies."""
    return +np.pi


def _trapz_axis(y: np.ndarray, x: np.ndarray, axis: int) -> np.ndarray:
    if hasattr(np, "trapezoid"):
        return np.trapezoid(y, x, axis=axis)
    return np.trapz(y, x, axis=axis)  # pragma: no cover


def _trapz(y: np.ndarray, x: np.ndarray) -> float:
    if hasattr(np, "trapezoid"):
        return float(np.trapezoid(y, x))
    return float(np.trapz(y, x))  # pragma: no cover


def _p_gl_panel_integrate(
    p_grid: np.ndarray,
    f_p: np.ndarray,
    split_points: np.ndarray,
    n_gl: int = 8,
) -> float:
    """GL panel quadrature for ∫ f(p) dp, splitting at kink positions.

    f_p is known on the dense p_grid (feature-enriched near the split points).
    GL nodes within each panel are evaluated via linear interpolation on p_grid.
    Splitting at the nesting momentum p*=kF_up-Q and at kF_dn removes the
    Q-dependent discretisation error that causes ReΓ⁻¹(Q,0) jitter.
    """
    p = np.asarray(p_grid, dtype=float)
    f = np.asarray(f_p, dtype=float)
    pts = np.asarray(split_points, dtype=float)
    pts = pts[(pts > p[0]) & (pts < p[-1])]
    # Keep the existing p-grid knots as panel boundaries.  The previous version
    # used only the requested split points, so a low-order GL rule could stride
    # across many sharp p-grid features and miss spectral weight.  Adding the
    # split points to the native knots preserves the ordinary trapezoid result
    # when no extra kink is present, while still allowing exact panel cuts at
    # p*=kF_up-Q or kF_dn when they fall between grid nodes.
    bds = np.unique(np.concatenate([p, pts]))
    xg, wg = np.polynomial.legendre.leggauss(max(2, int(n_gl)))
    total = 0.0
    for i in range(len(bds) - 1):
        a, b = float(bds[i]), float(bds[i + 1])
        if b <= a:
            continue
        mid = 0.5 * (a + b)
        half = 0.5 * (b - a)
        total += half * float(np.dot(wg, np.interp(mid + half * xg, p, f)))
    return total


def compute_impi_raw_totals_for_slice(
    omega_value: float,
    p_grid: np.ndarray,
    eps_grid: np.ndarray,
    adn_phi_slice: np.ndarray,
    aup_grid: np.ndarray,
    *,
    eps_integration_mode: str = "plain",
    p_integration_mode: str = "plain",
    p_split_points: np.ndarray | None = None,
    p_gl_n: int = 8,
) -> tuple[float, float, float]:
    """Compute raw radial totals for one omega slice."""
    integ_mode = str(eps_integration_mode).strip().lower()
    if integ_mode not in {"plain", "panel_kinks"}:
        raise ValueError("eps_integration_mode must be 'plain' or 'panel_kinks'.")

    prod = aup_grid * adn_phi_slice
    if integ_mode == "panel_kinks":
        i_p_thermal_raw = _trapz_axis_panel_kernel(
            prod,
            eps_grid,
            float(omega_value),
            _thermal_kernel_scalar_zero_temp,
        )
        i_p_med_raw = _trapz_axis_panel_kernel(
            prod,
            eps_grid,
            float(omega_value),
            _medium_kernel_scalar_zero_temp,
        )
    else:
        thermal = thermal_kernel_zero_temp(eps_grid, float(omega_value))
        medium = medium_kernel_zero_temp(eps_grid, float(omega_value))
        i_p_thermal_raw = _trapz_axis((thermal[None, :] * aup_grid) * adn_phi_slice, eps_grid, axis=1)
        i_p_med_raw = _trapz_axis((medium[None, :] * aup_grid) * adn_phi_slice, eps_grid, axis=1)
    i_p_no_thermal_raw = _trapz_axis(prod, eps_grid, axis=1)

    use_gl = (str(p_integration_mode).strip().lower() == "panel_kinks"
              and p_split_points is not None
              and len(np.asarray(p_split_points)) > 0)
    if use_gl:
        _sp = np.asarray(p_split_points, dtype=float)
        return (
            _p_gl_panel_integrate(p_grid, p_grid * i_p_thermal_raw, _sp, p_gl_n),
            _p_gl_panel_integrate(p_grid, p_grid * i_p_no_thermal_raw, _sp, p_gl_n),
            _p_gl_panel_integrate(p_grid, p_grid * i_p_med_raw, _sp, p_gl_n),
        )
    return (
        _trapz(p_grid * i_p_thermal_raw, p_grid),
        _trapz(p_grid * i_p_no_thermal_raw, p_grid),
        _trapz(p_grid * i_p_med_raw, p_grid),
    )


def finalize_impi_scan(
    omega_grid: np.ndarray,
    i_total_thermal_raw: np.ndarray,
    i_total_no_thermal_raw: np.ndarray,
    i_total_med_raw: np.ndarray,
) -> dict[str, np.ndarray]:
    """Convert raw totals into scaled totals and ImPi arrays."""
    i_total_thermal_scaled = np.asarray(i_total_thermal_raw, dtype=float) / ((2.0 * np.pi) ** 2)
    i_total_no_thermal_scaled = np.asarray(i_total_no_thermal_raw, dtype=float) / ((2.0 * np.pi) ** 2)
    i_total_med_scaled = np.asarray(i_total_med_raw, dtype=float) / ((2.0 * np.pi) ** 2)
    im_pi_thermal = impi_prefactor_sign() * i_total_thermal_scaled
    im_pi_no_thermal = -np.pi * i_total_no_thermal_scaled
    im_pi_med = impi_prefactor_sign() * i_total_med_scaled

    return {
        "omega": np.asarray(omega_grid, dtype=float),
        "i_total_thermal_raw": np.asarray(i_total_thermal_raw, dtype=float),
        "i_total_no_thermal_raw": np.asarray(i_total_no_thermal_raw, dtype=float),
        "i_total_med_raw": np.asarray(i_total_med_raw, dtype=float),
        "i_total_thermal_scaled": i_total_thermal_scaled,
        "i_total_no_thermal_scaled": i_total_no_thermal_scaled,
        "i_total_med_scaled": i_total_med_scaled,
        "im_pi_thermal": im_pi_thermal,
        "im_pi_no_thermal": im_pi_no_thermal,
        "im_pi_med": im_pi_med,
    }


def compute_impi_scan_from_slice_provider(
    omega_grid: np.ndarray,
    p_grid: np.ndarray,
    eps_grid: np.ndarray,
    aup_grid: np.ndarray,
    slice_provider,
    *,
    eps_integration_mode: str = "plain",
    p_integration_mode: str = "plain",
    p_split_points: np.ndarray | None = None,
    p_gl_n: int = 8,
    progress: bool = False,
) -> tuple[dict[str, np.ndarray], float]:
    """Compute ImPi(omega) by streaming translated slices one omega at a time."""
    n_omega = omega_grid.size
    i_total_thermal_raw = np.zeros(n_omega, dtype=float)
    i_total_no_thermal_raw = np.zeros(n_omega, dtype=float)
    i_total_med_raw = np.zeros(n_omega, dtype=float)
    support_mean_accum = 0.0

    for io, omega_value in enumerate(np.asarray(omega_grid, dtype=float)):
        slice_dn, support_frac = slice_provider(int(io), float(omega_value))
        support_mean_accum += float(np.mean(np.asarray(support_frac, dtype=float)))
        thermal_raw, no_thermal_raw, med_raw = compute_impi_raw_totals_for_slice(
            float(omega_value),
            p_grid,
            eps_grid,
            np.asarray(slice_dn, dtype=float),
            aup_grid,
            eps_integration_mode=eps_integration_mode,
            p_integration_mode=p_integration_mode,
            p_split_points=p_split_points,
            p_gl_n=int(p_gl_n),
        )
        i_total_thermal_raw[io] = thermal_raw
        i_total_no_thermal_raw[io] = no_thermal_raw
        i_total_med_raw[io] = med_raw
        if progress and ((io + 1) % max(1, n_omega // 10) == 0 or (io + 1) == n_omega):
            print(f"[info] omega slice {io + 1}/{n_omega} done (omega={float(omega_value):+.3f})")

    return finalize_impi_scan(
        omega_grid,
        i_total_thermal_raw,
        i_total_no_thermal_raw,
        i_total_med_raw,
    ), support_mean_accum / max(1, n_omega)


def compute_impi_scan_from_table_vectorized(
    omega_grid: np.ndarray,
    p_grid: np.ndarray,
    eps_grid: np.ndarray,
    aup_grid: np.ndarray,
    adn_phi_table: np.ndarray,
    support_frac_table: np.ndarray,
) -> tuple[dict[str, np.ndarray], float]:
    """Vectorized ImPi scan over all omega at once from a pre-built adn_phi table.

    Eliminates the per-omega Python loop. Uses plain-mode T=0 step-function kernels.

    Args:
        adn_phi_table: shape (n_omega, n_p, n_eps) — phi-integrated A_dn slices
        support_frac_table: shape (n_omega, n_p, n_eps) — support fractions
    """
    omega = np.asarray(omega_grid, dtype=float)
    eps = np.asarray(eps_grid, dtype=float)
    p = np.asarray(p_grid, dtype=float)
    aup = np.asarray(aup_grid, dtype=float)         # (n_p, n_eps)
    table = np.asarray(adn_phi_table, dtype=float)  # (n_omega, n_p, n_eps)

    prod = aup[None, :, :] * table  # (n_omega, n_p, n_eps)

    # T=0 medium kernel: Θ(-ε) + Θ(ε-ω), vectorized: (n_omega, n_eps)
    fe = (eps[None, :] < 0.0).astype(float)
    fwe = (eps[None, :] > omega[:, None]).astype(float)
    medium_k = fe + fwe  # (n_omega, n_eps)
    thermal_k = medium_k - 1.0

    # Integrate over eps (axis 2)
    i_p_thermal = _trapz_axis(thermal_k[:, None, :] * prod, eps, axis=2)    # (n_omega, n_p)
    i_p_no_thermal = _trapz_axis(prod, eps, axis=2)                          # (n_omega, n_p)
    i_p_med = _trapz_axis(medium_k[:, None, :] * prod, eps, axis=2)         # (n_omega, n_p)

    # Integrate over p (axis 1)
    if hasattr(np, "trapezoid"):
        i_total_thermal_raw = np.trapezoid(p[None, :] * i_p_thermal, p, axis=1)
        i_total_no_thermal_raw = np.trapezoid(p[None, :] * i_p_no_thermal, p, axis=1)
        i_total_med_raw = np.trapezoid(p[None, :] * i_p_med, p, axis=1)
    else:  # pragma: no cover
        i_total_thermal_raw = np.trapz(p[None, :] * i_p_thermal, p, axis=1)
        i_total_no_thermal_raw = np.trapz(p[None, :] * i_p_no_thermal, p, axis=1)
        i_total_med_raw = np.trapz(p[None, :] * i_p_med, p, axis=1)

    support_mean = float(np.mean(support_frac_table))
    return finalize_impi_scan(
        omega_grid,
        i_total_thermal_raw,
        i_total_no_thermal_raw,
        i_total_med_raw,
    ), support_mean




def _insert_axis_anchors_rows(
    x: np.ndarray,
    y_rows: np.ndarray,
    anchors: np.ndarray | list[float] | tuple[float, ...],
) -> tuple[np.ndarray, np.ndarray]:
    x_aug = np.asarray(x, dtype=float).reshape(-1)
    y_aug = np.asarray(y_rows, dtype=float)
    if y_aug.ndim != 2 or y_aug.shape[1] != x_aug.size:
        raise ValueError("y_rows must be 2D with shape (n_rows, x.size).")

    if x_aug.size < 2:
        return x_aug, y_aug

    dx_min = np.min(np.diff(x_aug))
    tol = max(1.0e-12, 1.0e-8 * float(dx_min))
    anchors_arr = np.asarray(anchors, dtype=float).reshape(-1)
    anchors_arr = anchors_arr[np.isfinite(anchors_arr)]
    if anchors_arr.size == 0:
        return x_aug, y_aug

    anchors_arr = np.unique(anchors_arr)
    anchors_arr = anchors_arr[(anchors_arr > float(x_aug[0]) + tol) & (anchors_arr < float(x_aug[-1]) - tol)]
    for aval in anchors_arr.tolist():
        if np.any(np.abs(x_aug - float(aval)) <= tol):
            continue
        j = int(np.searchsorted(x_aug, float(aval), side="left"))
        if not (0 < j < x_aug.size):
            continue
        x0 = float(x_aug[j - 1])
        x1 = float(x_aug[j])
        t = (float(aval) - x0) / max(x1 - x0, 1.0e-14)
        new_col = (1.0 - t) * y_aug[:, j - 1] + t * y_aug[:, j]
        x_aug = np.insert(x_aug, j, float(aval))
        y_aug = np.insert(y_aug, j, new_col, axis=1)
    return x_aug, y_aug


