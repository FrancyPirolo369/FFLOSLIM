def _trapz_axis_panel_kernel(
    y_prod: np.ndarray,
    x: np.ndarray,
    omega: float,
    kernel_scalar_fn,
) -> np.ndarray:
    x_aug, y_aug = _insert_axis_anchors_rows(x, y_prod, [0.0, float(omega)])
    if x_aug.size < 2:
        return np.zeros(y_aug.shape[0], dtype=float)

    out = np.zeros(y_aug.shape[0], dtype=float)
    break_vals = [0.0, float(omega)]
    break_idx: list[int] = [0]
    for aval in sorted(set(float(v) for v in break_vals if np.isfinite(v))):
        matches = np.where(np.isclose(x_aug, float(aval), atol=1.0e-12, rtol=0.0))[0]
        if matches.size > 0:
            idx = int(matches[0])
            if 0 < idx < x_aug.size - 1:
                break_idx.append(idx)
    break_idx.append(x_aug.size - 1)
    break_idx = sorted(set(break_idx))

    for i in range(len(break_idx) - 1):
        lo = int(break_idx[i])
        hi = int(break_idx[i + 1])
        if hi <= lo:
            continue
        x_seg = x_aug[lo : hi + 1]
        y_seg = y_aug[:, lo : hi + 1]
        eps_mid = 0.5 * (float(x_seg[0]) + float(x_seg[-1]))
        kval = float(kernel_scalar_fn(eps_mid, float(omega)))
        if kval == 0.0:
            continue
        out += kval * _trapz_axis(y_seg, x_seg, axis=1)
    return out


def kk_re_pv_linear(omega_grid: np.ndarray, im_vals: np.ndarray) -> np.ndarray:
    """Piecewise-linear principal-value KK on a strictly increasing omega grid."""
    x = np.asarray(omega_grid, dtype=float)
    y = np.asarray(im_vals, dtype=float)
    if x.ndim != 1 or y.ndim != 1 or x.size != y.size:
        raise ValueError("omega_grid and im_vals must be 1D arrays of equal size.")
    if x.size < 3:
        raise ValueError("Need at least 3 omega points for KK transform.")
    if np.any(np.diff(x) <= 0.0):
        raise ValueError("omega_grid must be strictly increasing.")

    n = x.size
    m = (y[1:] - y[:-1]) / (x[1:] - x[:-1])
    c = y[:-1] - m * x[:-1]
    out = np.full(n, np.nan, dtype=float)

    x0 = x[:-1][None, :]
    x1 = x[1:][None, :]
    mm = m[None, :]
    cc = c[None, :]
    w = x[1:-1][:, None]

    with np.errstate(divide="ignore", invalid="ignore"):
        seg = mm * (x1 - x0) + (mm * w + cc) * np.log(np.abs((x1 - w) / (x0 - w)))

    ridx = np.arange(n - 2)
    seg[ridx, ridx] = 0.0
    seg[ridx, ridx + 1] = 0.0
    total = np.sum(seg, axis=1)

    xl = x[:-2]
    xm = x[1:-1]
    xr = x[2:]
    yl = y[:-2]
    ym = y[1:-1]
    yr = y[2:]
    m_left = (ym - yl) / (xm - xl)
    m_right = (yr - ym) / (xr - xm)
    local = m_left * (xm - xl) + m_right * (xr - xm) + ym * np.log((xr - xm) / (xm - xl))
    out[1:-1] = (total + local) / np.pi
    out[0] = out[1]
    out[-1] = out[-2]
    return out


def kk_with_powerlaw_tail(
    omega_grid: np.ndarray,
    im_vals: np.ndarray,
    *,
    alpha: float,
    n_boundary: int = 3,
) -> np.ndarray:
    """KK transform with analytic tail correction for Im ~ -C/omega^alpha.

    alpha must be supplied by the caller from the known proxy asymptotics —
    it is a physics input, not fitted from data.  C is read off the boundary:
      C_pos = -Im(omega_max) * omega_max^alpha   (positive tail)
      C_neg = -Im(omega_min) * |omega_min|^alpha  (negative tail)
    averaged over n_boundary edge points for noise robustness.

    For alpha <= 1 (log-divergent tail) no correction is applied.

    Correction formula (to next order in nu/omega_max):
      delta_Re(nu) ~ C / (pi*(alpha-1)*omega_max^(alpha-1))
                     * (1 + alpha/(alpha-1) * nu/omega_max)
    """
    if alpha <= 1.0:
        return kk_re_pv_linear(omega_grid, im_vals)

    x = np.asarray(omega_grid, dtype=float)
    y = np.asarray(im_vals, dtype=float)
    re = kk_re_pv_linear(x, y)

    nb = max(1, int(n_boundary))
    omega_max = float(x[-1])
    omega_min = float(np.abs(x[0]))

    c_pos = float(np.mean(-y[-nb:] * x[-nb:] ** alpha))
    c_neg = float(np.mean(-y[:nb] * np.abs(x[:nb]) ** alpha))

    nu = x.copy()
    denom = (alpha - 1.0) * omega_max ** (alpha - 1.0)

    corr_pos = c_pos / (np.pi * denom)
    re += corr_pos * (1.0 + (alpha / (alpha - 1.0)) * nu / omega_max)

    corr_neg = c_neg / (np.pi * denom)
    re -= corr_neg * (1.0 - (alpha / (alpha - 1.0)) * nu / omega_min)

    return re


def kk_re_with_optional_powerlaw_tail(
    omega_source: np.ndarray,
    im_source: np.ndarray,
    omega_output: np.ndarray,
    *,
    kk_pad: float,
    kk_oversample: float,
    tail_mode: str,
    kk_n_max: int | None = None,
    tail_alpha: float | None = None,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Build a KK grid and reconstruct Re with an optional two-sided power tail.

    If ``tail_alpha`` is supplied, the exterior contribution is evaluated from
    the actual source-window boundaries.  In that mode ``kk_pad`` and
    ``tail_mode`` are deliberately ignored for the exterior region: padding with
    zeros or held boundary values would corrupt the coefficients of the
    analytic left/right tails.
    """
    alpha = None if tail_alpha is None else float(tail_alpha)
    if alpha is None or not np.isfinite(alpha):
        omega_kk, im_kk = build_kk_input_grid(
            omega_source,
            im_source,
            omega_output,
            kk_pad=float(kk_pad),
            kk_oversample=float(kk_oversample),
            tail_mode=str(tail_mode),
            kk_n_max=kk_n_max,
        )
        re_kk = kk_re_pv_linear(omega_kk, im_kk)
        return omega_kk, im_kk, re_kk

    # Oversample inside the computed source window only.  The exterior is
    # supplied analytically by kk_with_powerlaw_tail using the two boundaries.
    omega_kk, im_kk = build_kk_input_grid(
        omega_source,
        im_source,
        omega_source,
        kk_pad=0.0,
        kk_oversample=float(kk_oversample),
        tail_mode="zero",
        kk_n_max=kk_n_max,
    )
    re_kk = kk_with_powerlaw_tail(omega_kk, im_kk, alpha=alpha)
    return omega_kk, im_kk, re_kk


def _uniform_step(x: np.ndarray) -> float:
    dx = np.diff(np.asarray(x, dtype=float))
    dx = dx[dx > 0.0]
    if dx.size == 0:
        return 1.0
    return float(np.median(dx))


def build_kk_input_grid(
    omega_source: np.ndarray,
    im_source: np.ndarray,
    omega_output: np.ndarray,
    *,
    kk_pad: float,
    kk_oversample: float,
    tail_mode: str,
    kk_n_max: int | None = None,
    tail_eval: Callable[[np.ndarray], np.ndarray] | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Build the omega/im arrays used for KK, optionally padded and oversampled.

    `tail_mode="analytic"` or `tail_mode="analytic_proxy"` uses `tail_eval`
    to supply the exterior omega tails instead of a constant extrapolation.
    """
    x_src = np.asarray(omega_source, dtype=float)
    y_src = np.asarray(im_source, dtype=float)
    x_out = np.asarray(omega_output, dtype=float)
    if x_src.ndim != 1 or y_src.ndim != 1 or x_src.size != y_src.size:
        raise ValueError("omega_source and im_source must be 1D arrays with equal size.")
    if x_out.ndim != 1 or x_out.size < 2:
        raise ValueError("omega_output must be 1D with at least 2 points.")
    if np.any(np.diff(x_src) <= 0.0):
        order = np.argsort(x_src)
        x_src = x_src[order]
        y_src = y_src[order]

    pad = max(float(kk_pad), 0.0)
    ov = max(float(kk_oversample), 1.0)
    x_min_target = float(x_out[0]) - pad
    x_max_target = float(x_out[-1]) + pad
    x_min = min(float(x_src[0]), x_min_target)
    x_max = max(float(x_src[-1]), x_max_target)

    dx = max(_uniform_step(x_src) / ov, 1.0e-12)
    n = max(3, int(round((x_max - x_min) / dx)) + 1)
    if kk_n_max is not None:
        kk_n_cap = max(int(kk_n_max), 3)
        if n > kk_n_cap:
            n = kk_n_cap
    x_kk = np.linspace(x_min, x_max, n, dtype=float)

    tail = str(tail_mode).strip().lower()
    if tail == "hold":
        y_left = float(y_src[0])
        y_right = float(y_src[-1])
    elif tail == "zero":
        y_left = 0.0
        y_right = 0.0
    elif tail in {"analytic", "analytic_proxy"}:
        if tail_eval is None:
            raise ValueError("tail_mode='analytic' requires tail_eval.")
        y_kk = np.interp(x_kk, x_src, y_src)
        left_mask = x_kk < float(x_src[0])
        right_mask = x_kk > float(x_src[-1])
        if np.any(left_mask):
            y_kk[left_mask] = np.asarray(tail_eval(x_kk[left_mask]), dtype=float)
        if np.any(right_mask):
            y_kk[right_mask] = np.asarray(tail_eval(x_kk[right_mask]), dtype=float)
        return x_kk, y_kk
    else:
        raise ValueError("tail_mode must be 'zero', 'hold', or 'analytic'.")

    y_kk = np.interp(x_kk, x_src, y_src, left=y_left, right=y_right)
    return x_kk, y_kk


def g0_inverse(omega: np.ndarray, q: float, eps0: float, mu_up: float, mu_dn: float, eta_gamma: float) -> np.ndarray:
    w_c = np.asarray(omega, dtype=float) + 1j * float(eta_gamma)
    return -(1.0 / (8.0 * np.pi)) * np.log((float(q) * float(q) / 2.0 - float(mu_up) - float(mu_dn) -w_c) / float(eps0))


def kk_sigma_gamma_asymptote(
    omega: np.ndarray,
    im_sigma: np.ndarray,
    *,
    k_ext: float,
    eps0: float,
    mu_up: float,
    mu_dn: float,
    eta_gamma: float,
    n_internal: float,
    kk_pad: float,
    kk_oversample: float,
    kk_n_max: int | None = None,
) -> np.ndarray:
    """ReSigma via KK with the analytic n_internal*Gamma(k,omega) asymptote removed.

    The pair-fluctuation ImSigma has a slow ~1/ln^2(omega) UV tail (the pair
    continuum / contact tail) that makes a plain KK non-convergent and the
    powerlaw exterior wrong.  The high-frequency expansion of the convolution
    gives Sigma(k,omega) -> n_internal * Gamma(k,omega) (Gamma the vacuum pair
    propagator at the external momentum, n_internal = mu_internal/4pi the
    opposite-spin occupation).  Gamma is causal so Re(Gamma) is the exact KK of
    Im(Gamma), known in closed form (= Re(1/g0_inverse)).  Subtract
    n_internal*Im(Gamma), KK the fast-decaying residual numerically (zero tail),
    add back n_internal*Re(Gamma).  Validated: residual ~ omega^-1.6 and
    KK[residual](0) plateaus for window >= 24 while plain KK keeps drifting.
    """
    w = np.asarray(omega, dtype=float)
    gamma = 1.0 / g0_inverse(w, float(k_ext), float(eps0), float(mu_up), float(mu_dn), float(eta_gamma))
    im_asy = float(n_internal) * np.imag(gamma)
    re_asy = float(n_internal) * np.real(gamma)
    residual = np.asarray(im_sigma, dtype=float) - im_asy
    # KK the residual on the NATIVE (split, dense-near-0) grid with the exact
    # piecewise-linear principal value.  Do NOT re-grid to uniform (oversample):
    # that coarsens the dense near-omega=0 region and smears the sharp QP peak,
    # breaking the window-independence.  The residual decays fast (~omega^-1.6)
    # so the implicit zero exterior of kk_re_pv_linear is harmless.
    return re_asy + kk_re_pv_linear(w, residual)


def proxy_medium_pi_from_gamma(
    omega: np.ndarray,
    *,
    q: float,
    eps0: float,
    mu_up: float,
    mu_dn: float,
    eta_gamma: float,
) -> np.ndarray:
    """Return the analytic proxy medium piece Pi_med = g0^{-1} - Gamma_proxy^{-1}.

    Important:
    This is not the full pair bubble including the vacuum contribution. In the
    notation of the 2D FFLO paper, the proxy Gamma^{-1} already contains the
    vacuum term, so subtracting it from g0^{-1} leaves only the Fermi-surface
    / medium contribution.
    """
    analytical_configuration.update(
        epsilon_0=float(eps0),
        mu_up=float(mu_up),
        mu_down=float(mu_dn),
    )
    w = np.asarray(omega, dtype=float)
    gamma_vals = np.asarray(
        analytical_gamma(float(q), w + 1j * float(eta_gamma)),
        dtype=complex,
    )
    g0_inv = g0_inverse(
        w,
        q=float(q),
        eps0=float(eps0),
        mu_up=float(mu_up),
        mu_dn=float(mu_dn),
        eta_gamma=float(eta_gamma),
    )
    with np.errstate(divide="ignore", invalid="ignore"):
        inv_gamma = 1.0 / gamma_vals
    return np.asarray(g0_inv - inv_gamma, dtype=complex)




