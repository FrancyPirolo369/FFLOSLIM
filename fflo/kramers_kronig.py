r"""Compute convolution integrals using a precomputed translated A_down table.

Uses:
- precomputed table: A_down_phi_integral(omega, p, eps) = ∫ dphi A_down(...)
- spin-up cube: A_up(k, omega)

At fixed external omega, computes
  I_p_raw(p) = ∫ d eps (f(eps) + f(omega-eps)) A_up(p,eps) A_down_phi_integral(omega,p,eps)

and total radial integral
  I_total_raw = ∫ p dp I_p_raw(p).

Also reports normalized versions:
  I_p_scaled   = I_p_raw / (2pi)^2
  I_total_scaled = I_total_raw / (2pi)^2
  ImPi_est = +pi * I_total_scaled

Additionally splits epsilon contributions:
  I_pos_raw = ∫ p dp ∫_{eps>0}   A_up * A_down_phi_int
  I_neg_raw = ∫ p dp ∫_{eps<0}   A_up * A_down_phi_int
so that (for the thermal integrand):
  I_thermal_raw = I_pos_raw + I_neg_raw
"""

